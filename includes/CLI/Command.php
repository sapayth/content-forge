<?php
/**
 * DESCRIPTION: WP-CLI `wp cforge` commands to list, delete and report on generated content.
 * DESCRIPTION: Every command runs through the plugin's own REST routes, so the CLI matches the admin.
 *
 * @package ContentForge
 * @since   1.8.0
 */

namespace ContentForge\CLI;

use WP_CLI;
use WP_CLI\Utils;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Generate, list and delete Content Forge content.
 *
 * ## EXAMPLES
 *
 *     # Seed a site, then clean it up again.
 *     $ wp cforge generate posts --count=40 --comment_status=open
 *     $ wp cforge generate comments --count=120 --status=approve
 *     $ wp cforge delete posts --all --yes
 *
 * @since 1.8.0
 */
class Command {

	/**
	 * Largest page the REST list routes return.
	 *
	 * @since 1.8.0
	 *
	 * @var int
	 */
	const LIST_PAGE_SIZE = 50;

	/**
	 * REST routes for each content kind, relative to the cforge/v1 namespace.
	 *
	 * @since 1.8.0
	 *
	 * @var array<string, array{list:string,bulk:string,item:string,id_field:string,fields:string}>
	 */
	const TYPES = [
		'posts'    => [
			'list'     => 'posts/list',
			'bulk'     => 'posts/bulk',
			'item'     => 'posts/',
			'id_field' => 'ID',
			'fields'   => 'ID,title,type,author,date',
		],
		'users'    => [
			'list'     => 'users',
			'bulk'     => 'users/bulk',
			'item'     => 'users/',
			'id_field' => 'ID',
			'fields'   => 'ID,user_login,user_email,role',
		],
		'comments' => [
			'list'     => 'comments',
			'bulk'     => 'comments/bulk',
			'item'     => 'comments/',
			'id_field' => 'id',
			'fields'   => 'id,post_id,author_name,status,date',
		],
		'terms'    => [
			'list'     => 'taxonomy/list',
			'bulk'     => 'taxonomy/bulk',
			'item'     => 'taxonomy/',
			'id_field' => 'ID',
			'fields'   => 'ID,title,taxonomy,date',
		],
	];

	/**
	 * Lists content generated by Content Forge.
	 *
	 * ## OPTIONS
	 *
	 * <type>
	 * : Kind of content to list.
	 * ---
	 * options:
	 *   - posts
	 *   - users
	 *   - comments
	 *   - terms
	 * ---
	 *
	 * [--post_type=<type>]
	 * : Only list this post type. Posts only.
	 *
	 * [--fields=<fields>]
	 * : Comma-separated fields to show.
	 *
	 * [--format=<format>]
	 * : Output format.
	 * ---
	 * default: table
	 * options:
	 *   - table
	 *   - csv
	 *   - json
	 *   - ids
	 *   - count
	 * ---
	 *
	 * ## EXAMPLES
	 *
	 *     $ wp cforge list posts --post_type=page
	 *     $ wp cforge list users --format=ids
	 *
	 * @subcommand list
	 *
	 * @since 1.8.0
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 *
	 * @return void
	 */
	public function list_( $args, $assoc_args ) {
		$type   = $args[0];
		$items  = self::fetch_tracked( $type, Utils\get_flag_value( $assoc_args, 'post_type', '' ) );
		$format = Utils\get_flag_value( $assoc_args, 'format', 'table' );

		if ( 'count' === $format ) {
			WP_CLI::line( (string) count( $items ) );
			return;
		}

		if ( 'ids' === $format ) {
			WP_CLI::line( implode( ' ', wp_list_pluck( $items, self::TYPES[ $type ]['id_field'] ) ) );
			return;
		}

		$fields = Utils\get_flag_value( $assoc_args, 'fields', self::TYPES[ $type ]['fields'] );
		Utils\format_items( $format, $items, $fields );
	}

	/**
	 * Deletes content generated by Content Forge. Never touches anything else.
	 *
	 * ## OPTIONS
	 *
	 * <type>
	 * : Kind of content to delete.
	 * ---
	 * options:
	 *   - posts
	 *   - users
	 *   - comments
	 *   - terms
	 * ---
	 *
	 * [<id>...]
	 * : IDs to delete. IDs Content Forge did not generate are skipped with a warning.
	 *
	 * [--all]
	 * : Delete everything of this kind that Content Forge generated.
	 *
	 * [--yes]
	 * : Skip the confirmation prompt for --all.
	 *
	 * [--dry-run]
	 * : List what would be deleted, and delete nothing.
	 *
	 * ## EXAMPLES
	 *
	 *     $ wp cforge delete posts --all --yes
	 *     $ wp cforge delete users 12 13 14
	 *     $ wp cforge delete posts --all --dry-run
	 *
	 * @since 1.8.0
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 *
	 * @return void
	 */
	public function delete( $args, $assoc_args ) {
		$type    = array_shift( $args );
		$routes  = self::TYPES[ $type ];
		$all     = Utils\get_flag_value( $assoc_args, 'all', false );
		$dry_run = Utils\get_flag_value( $assoc_args, 'dry-run', false );

		if ( $all && $dry_run ) {
			// ponytail: previews the list route, which hides trashed/auto-draft posts that the
			// bulk route still deletes; add a count route if the gap ever matters.
			$this->report_dry_run( $type, self::fetch_tracked( $type ) );
			return;
		}

		if ( $all ) {
			WP_CLI::confirm(
				/* translators: %s: content kind, e.g. posts */
				sprintf( __( 'Delete all %s generated by Content Forge?', 'content-forge' ), $type ),
				$assoc_args
			);
			$data = self::dispatch( 'DELETE', $routes['bulk'] );
			/* translators: 1: number deleted, 2: content kind */
			WP_CLI::success( sprintf( __( 'Deleted %1$d %2$s.', 'content-forge' ), (int) $data['deleted'], $type ) );
			return;
		}

		if ( empty( $args ) ) {
			WP_CLI::error( __( 'Pass one or more IDs, or --all.', 'content-forge' ) );
		}

		// The user and term item routes delete any ID, so only pass on IDs we generated.
		$tracked_items = self::fetch_tracked( $type );
		$tracked       = array_map( 'absint', wp_list_pluck( $tracked_items, $routes['id_field'] ) );
		$would_delete  = [];
		$deleted       = 0;

		foreach ( $args as $arg ) {
			if ( ! ctype_digit( (string) $arg ) ) {
				/* translators: %s: the argument given */
				WP_CLI::warning( sprintf( __( 'Skipped "%s": not an ID.', 'content-forge' ), $arg ) );
				continue;
			}

			$id = (int) $arg;
			if ( ! in_array( $id, $tracked, true ) ) {
				/* translators: %d: object ID */
				WP_CLI::warning( sprintf( __( 'Skipped %d: not generated by Content Forge.', 'content-forge' ), $id ) );
				continue;
			}

			if ( $dry_run ) {
				$would_delete[] = $tracked_items[ array_search( $id, $tracked, true ) ];
				continue;
			}

			$data = self::dispatch( 'DELETE', $routes['item'] . $id, [], false );
			if ( is_wp_error( $data ) ) {
				/* translators: 1: object ID, 2: error message */
				WP_CLI::warning( sprintf( __( 'Skipped %1$d: %2$s', 'content-forge' ), $id, $data->get_error_message() ) );
				continue;
			}
			$deleted += (int) $data['deleted'];
		}

		if ( $dry_run ) {
			$this->report_dry_run( $type, $would_delete );
			return;
		}

		/* translators: 1: number deleted, 2: content kind */
		WP_CLI::success( sprintf( __( 'Deleted %1$d %2$s.', 'content-forge' ), $deleted, $type ) );
	}

	/**
	 * Shows tracked content counts and Autopilot health, as on the Dashboard.
	 *
	 * ## OPTIONS
	 *
	 * [--format=<format>]
	 * : Output format.
	 * ---
	 * default: table
	 * options:
	 *   - table
	 *   - json
	 * ---
	 *
	 * @since 1.8.0
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Associative arguments.
	 *
	 * @return void
	 */
	public function status( $args, $assoc_args ) {
		$data   = self::dispatch( 'GET', 'dashboard' );
		$status = [
			'counts'    => $data['counts'],
			'total'     => $data['total'],
			'autopilot' => $data['autopilot'],
		];

		if ( 'json' === Utils\get_flag_value( $assoc_args, 'format', 'table' ) ) {
			WP_CLI::line( wp_json_encode( $status ) );
			return;
		}

		$rows = [];
		foreach ( $status['counts'] as $kind => $count ) {
			$rows[] = [
				'item'  => $kind,
				'value' => $count,
			];
		}
		$rows[] = [
			'item'  => 'total',
			'value' => $status['total'],
		];

		$autopilot = $status['autopilot'];
		$rows[]    = [
			'item'  => 'autopilot_enabled',
			'value' => $autopilot['enabled'] ? 'yes' : 'no',
		];
		$rows[]    = [
			'item'  => 'autopilot_active',
			'value' => $autopilot['active'],
		];
		$rows[]    = [
			'item'  => 'autopilot_paused',
			'value' => $autopilot['paused'],
		];
		$rows[]    = [
			'item'  => 'autopilot_last_run',
			'value' => null === $autopilot['minutes_since']
				? __( 'never', 'content-forge' )
				/* translators: %d: minutes since the last dispatcher run */
				: sprintf( __( '%d min ago', 'content-forge' ), $autopilot['minutes_since'] ),
		];

		Utils\format_items( 'table', $rows, [ 'item', 'value' ] );
	}

	/**
	 * Show the items a delete would remove.
	 *
	 * @since 1.8.0
	 *
	 * @param string $type  Content kind, a key of self::TYPES.
	 * @param array  $items List items as the REST list route returns them.
	 *
	 * @return void
	 */
	private function report_dry_run( $type, $items ) {
		if ( $items ) {
			Utils\format_items( 'table', $items, self::TYPES[ $type ]['fields'] );
		}
		/* translators: 1: number of items, 2: content kind */
		WP_CLI::success( sprintf( __( 'Dry run: would delete %1$d %2$s.', 'content-forge' ), count( $items ), $type ) );
	}

	/**
	 * Run a cforge/v1 REST route in-process and return its response data.
	 *
	 * @since 1.8.0
	 *
	 * @param string $method        HTTP method.
	 * @param string $route         Route relative to cforge/v1, e.g. 'posts/bulk'.
	 * @param array  $params        Query params for GET, JSON body otherwise.
	 * @param bool   $exit_on_error Exit with the REST error message (default), or return a WP_Error.
	 *
	 * @return array|\WP_Error Response data.
	 */
	public static function dispatch( $method, $route, $params = [], $exit_on_error = true ) {
		self::ensure_user();

		$request = new \WP_REST_Request( $method, '/cforge/v1/' . $route );
		if ( 'GET' === $method ) {
			$request->set_query_params( $params );
		} else {
			$request->set_header( 'Content-Type', 'application/json' );
			$request->set_body( wp_json_encode( $params ) );
		}

		$response = rest_do_request( $request );
		$data     = rest_get_server()->response_to_data( $response, false );

		if ( ! $response->is_error() ) {
			return $data;
		}

		$message = isset( $data['message'] ) ? $data['message'] : __( 'Request failed.', 'content-forge' );
		if ( $exit_on_error ) {
			WP_CLI::error( $message );
		}

		return new \WP_Error( 'cforge_cli_request_failed', $message );
	}

	/**
	 * Fetch every tracked item of a kind, walking the paginated list route.
	 *
	 * @since 1.8.0
	 *
	 * @param string $type      Content kind, a key of self::TYPES.
	 * @param string $post_type Optional post type filter (posts only).
	 *
	 * @return array List items as the REST route returns them.
	 */
	public static function fetch_tracked( $type, $post_type = '' ) {
		$params = [ 'per_page' => self::LIST_PAGE_SIZE ];
		if ( 'posts' === $type && $post_type ) {
			$params['post_types'] = $post_type;
		}

		$items = [];
		for ( $page = 1; ; $page++ ) {
			$params['page'] = $page;
			$data           = self::dispatch( 'GET', self::TYPES[ $type ]['list'], $params );
			$batch          = isset( $data['items'] ) ? $data['items'] : [];
			$items          = array_merge( $items, $batch );

			if ( count( $batch ) < self::LIST_PAGE_SIZE ) {
				return $items;
			}
		}
	}

	/**
	 * Act as the --user given, or else the first administrator.
	 *
	 * @since 1.8.0
	 *
	 * @return void
	 */
	private static function ensure_user() {
		if ( get_current_user_id() ) {
			return;
		}

		$admins = get_users(
			[
				'role'    => 'administrator',
				'orderby' => 'ID',
				'order'   => 'ASC',
				'number'  => 1,
			]
		);
		if ( empty( $admins ) ) {
			WP_CLI::error( __( 'No administrator found. Pass --user=<id|login|email>.', 'content-forge' ) );
		}

		wp_set_current_user( $admins[0]->ID );
		// STDERR, so --porcelain and --format=json output stays clean.
		WP_CLI::warning(
			/* translators: 1: user login, 2: user ID */
			sprintf( __( 'No --user given; running as %1$s (ID %2$d).', 'content-forge' ), $admins[0]->user_login, $admins[0]->ID )
		);
	}
}
